"""Offline area-weighted spawn spans from the existing full-resolution terrain.
No runtime world scan; original Natural Earth land/lake mask remains unchanged.
Regions are explicit gameplay geography, not political borders.
"""
from pathlib import Path
import math,struct,json,hashlib
from generate_earth import literal
r=Path(__file__).resolve().parents[1];w,h=8192,4096
raw=(r/'build/earth-terrain.bin').read_bytes();assert len(raw)==w*h
manifest=json.loads((r/'data/earth-topology-manifest.json').read_text())
assert hashlib.sha256(raw).hexdigest()==manifest['terrain_sha256']
names=['North America','South America','Europe','Africa','Asia','Oceania']
def region(lon,lat):
 if lat < -60:return 0
 if (lon < -110 and lat < 25) or (lon>=110 and lat < -10) or (lon>=130 and lat<0) or (lon>=160 and lat<20):return 6
 if lon < -168 and lat>55:return 5
 if lon < -30:return 1 if lat>=12 or lon<-77 and lat>=7 else 2
 south=36 if lon < -5 else 38 if lon<15 else 35 if lon<28 else 42 if lon<45 else 55
 if -25<=lon<60 and lat>=south:return 3
 east=35 if lat>=30 else 32+(30-lat)*.65 if lat>=12 else 60
 if -30<=lon<east and lat<38:return 4
 return 5
regions=[bytearray()for _ in names];weights=[0.]*6;counts=[0]*6
for y in range(h):
 lat=90-(y+.5)*180/h
 if lat < -60:continue
 weight=math.cos(math.radians(lat));row=raw[y*w:(y+1)*w];x=0
 while x<w:
  b=row[x]
  if not b&128 or b&31==31:x+=1;continue
  first=x;k=region((x+.5)*360/w-180,lat)
  x+=1
  while x<w and row[x]&128 and row[x]&31!=31 and region((x+.5)*360/w-180,lat)==k:x+=1
  if k:
   length=x-first;weights[k-1]+=length*weight;counts[k-1]+=length
   regions[k-1]+=struct.pack('<IHd',y*w+first,length,weights[k-1])
parts=['--!strict','-- Generated by scripts/generate_spawn_atlas.py from existing Natural Earth terrain.',
 '-- Original adaptation; preserve LICENSE/NOTICE (AGPL-3.0). No gameplay grid changes.',
 'return {Width=8192,Height=4096,MaskHash="'+manifest['mask_sha256']+'",Regions={']
for name,data,weight in zip(names,regions,weights):parts.append('{Name='+json.dumps(name)+',Weight='+repr(weight)+',Spans='+literal(data)+'},')
parts+=['}}']
(r/'src/server/OpenFront/SpawnAtlas.luau').write_text('\n'.join(parts))
info={'terrain_sha256':manifest['terrain_sha256'],'regions':[{'name':n,'cells':c,'weighted_cells':a,'share':a/sum(weights),'spans':len(d)//14}for n,c,a,d in zip(names,counts,weights,regions)],'bytes':sum(map(len,regions)),'antarctica_cutoff_latitude':-60,'method':'exact playable row spans, cos(latitude) area weighting, explicit gameplay continent boundaries'}
(r/'data/spawn-atlas-manifest.json').write_text(json.dumps(info,indent=2));print(json.dumps(info,indent=2))
